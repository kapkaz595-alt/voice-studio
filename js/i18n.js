function detectLang() {
  try {
    const saved = localStorage.getItem('vs-lang');
    if (saved && DICT[saved]) return saved;
  } catch (e) { /* 忽略 */ }
  const n = (navigator.language || '').toLowerCase();
  if (n.startsWith('zh')) return 'zh';
  if (n.startsWith('kk')) return 'kk';
  if (n.startsWith('ru')) return 'ru';
  return 'en';
}

let lang = detectLang();
const listeners = [];

export const getLang = () => lang;
export const onLangChange = fn => listeners.push(fn);

export function t(key, params) {
  let s = (DICT[lang] && DICT[lang][key]) ?? DICT.zh[key] ?? key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? params[k] : m));
  return s;
}

// 设置动态文字，并记住 key，切换语言时自动重新翻译。key 为空则清空
export function setText(el, key, params) {
  if (!key) {
    el.textContent = '';
    delete el.dataset.k;
    delete el.dataset.p;
    return;
  }
  el.dataset.k = key;
  if (params) el.dataset.p = JSON.stringify(params);
  else delete el.dataset.p;
  el.textContent = t(key, params);
}

export function applyAll(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(e => { e.textContent = t(e.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach(e => { e.placeholder = t(e.dataset.i18nPh); });
  root.querySelectorAll('[data-k]').forEach(e => {
    e.textContent = t(e.dataset.k, e.dataset.p ? JSON.parse(e.dataset.p) : undefined);
  });
}

export function setLang(l) {
  if (!DICT[l]) return;
  lang = l;
  try { localStorage.setItem('vs-lang', l); } catch (e) { /* 忽略 */ }
  document.documentElement.lang = l;
  applyAll();
  listeners.forEach(fn => fn());
}

document.documentElement.lang = lang;
